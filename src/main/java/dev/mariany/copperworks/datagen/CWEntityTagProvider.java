package dev.mariany.copperworks.datagen;

import dev.mariany.copperworks.tag.CWTags;
import net.fabricmc.fabric.api.datagen.v1.FabricDataOutput;
import net.fabricmc.fabric.api.datagen.v1.provider.FabricTagProvider;
import net.minecraft.registry.RegistryWrapper;

import java.util.concurrent.CompletableFuture;

public class CWEntityTagProvider extends FabricTagProvider.EntityTypeTagProvider {
    public CWEntityTagProvider(
            FabricDataOutput output,
            CompletableFuture<RegistryWrapper.WrapperLookup> registriesFuture
    ) {
        super(output, registriesFuture);
    }

    @Override
    protected void configure(RegistryWrapper.WrapperLookup wrapperLookup) {
        valueLookupBuilder(CWTags.Entities.STICKY_IMMUNE);
    }
}
